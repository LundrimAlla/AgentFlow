"""Export registered live API and TS types without loading credentials or making requests."""

import json
from pathlib import Path
from typing import Any

from pydantic import SecretStr

from app.core.config import Settings
from app.main import create_app


def ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(ts(part) for part in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "object":
        required = schema.get("required", [])
        fields = [
            f"  {json.dumps(key)}{'' if key in required else '?'}: {ts(value)};"
            for key, value in schema.get("properties", {}).items()
        ]
        return "{\n" + "\n".join(fields) + "\n}"
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    if kind in ("string", "boolean", "null"):
        return str(kind)
    if kind in ("number", "integer"):
        return "number"
    raise ValueError(f"Unsupported schema: {schema}")


settings = Settings(
    _env_file=None,
    app_env="test",
    live_enabled=True,
    rag_enabled=True,
    rag_database_url=SecretStr("postgresql://placeholder@localhost/placeholder"),
    gemini_api_key=SecretStr("placeholder"),
    turnstile_secret_key=SecretStr("placeholder"),
    upstash_redis_rest_url="https://placeholder.upstash.io",
    upstash_redis_rest_token=SecretStr("placeholder"),
    rate_limit_hmac_secret=SecretStr("x" * 32),
)
contract = create_app(settings).openapi()
root = Path(__file__).resolve().parent.parent
(root / "docs/openapi.json").write_text(json.dumps(contract, indent=2) + "\n", encoding="utf-8")
types = "// Generated by backend/export_contract.py. Do not edit.\n\n"
types += (
    "\n\n".join(
        f"export type {name} = {ts(schema)};"
        for name, schema in contract["components"]["schemas"].items()
    )
    + "\n"
)
destination = root / "frontend/app/live/api.generated.ts"
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text(types, encoding="utf-8")
